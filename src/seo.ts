/** Social preview image per page family (generated by scripts/og-images.cjs). */
export function ogImage(route: string) {
  const family = route.startsWith("/services")
    ? "services"
    : route.startsWith("/products")
      ? "products"
      : ["/about", "/industries", "/process", "/faq"].includes(route)
        ? "company"
        : ["/blueprint", "/portal-demo"].includes(route)
          ? "resources"
          : route === "/contact"
            ? "contact"
            : "default";
  return `${SITE_URL}/og/${family}.png`;
}

